//! Removal of oxide-owned `build_runner` outputs, so the oxide builders rerun.

use std::path::{Path, PathBuf};

/// Marker prefix the oxide Dart builder writes at the top of `lib/oxide.dart`.
const GENERATED_ENTRYPOINT_MARKER: &str = "// Generated by oxide_generator";

/// Suffix of the per-file glue the oxide builder emits.
const GENERATED_FILE_SUFFIX: &str = ".oxide.g.dart";

/// Delete oxide-owned build_runner outputs so the oxide builders rerun instead
/// of serving stale cache entries.
///
/// The oxide Dart builders read route metadata from `rust/target/oxide_routes`
/// over `dart:io`, which is invisible to build_runner's asset graph. So a route
/// change does not invalidate the cache, and these outputs must be cleared
/// before re-running the builder.
///
/// Only oxide-owned files are touched. `lib/oxide.dart` is removed only when it
/// carries the generated marker, so a hand-written file of the same name is left
/// alone.
///
/// This deletes before anything has regenerated the files. Call
/// [`GlueSnapshot::capture`] first and `restore` it if the subsequent codegen
/// step fails, otherwise a codegen failure leaves the project with no glue at
/// all. See [`GlueSnapshot`].
pub fn nuke(root: &Path) {
    let gen_dir = root.join("lib/oxide_generated");
    if gen_dir.is_dir() {
        let _ = std::fs::remove_dir_all(&gen_dir);
    }

    let entry = root.join("lib/oxide.dart");
    if entry.is_file()
        && std::fs::read_to_string(&entry).is_ok_and(|c| c.starts_with(GENERATED_ENTRYPOINT_MARKER))
    {
        let _ = std::fs::remove_file(&entry);
    }

    for p in find_generated_files(&root.join("lib")) {
        let _ = std::fs::remove_file(&p);
    }
}

/// Paths under `lib` matching the per-file glue suffix.
fn find_generated_files(lib: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let mut stack = vec![lib.to_path_buf()];
    while let Some(d) = stack.pop() {
        let Ok(rd) = std::fs::read_dir(&d) else {
            continue;
        };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
                continue;
            }
            if p.file_name()
                .is_some_and(|n| n.to_string_lossy().ends_with(GENERATED_FILE_SUFFIX))
            {
                found.push(p);
            }
        }
    }
    found
}

/// `relative path -> file contents`
type Files = Vec<(PathBuf, Vec<u8>)>;

/// A saved copy of the glue that [`nuke`] is about to delete.
///
/// `nuke` runs before `dart run build_runner build` because the builder caches
/// must be busted. If that build then fails, the project is left with no oxide
/// glue and no way to recover it, since the outputs are gitignored. Capturing
/// first and restoring on failure makes the destructive step recoverable.
pub struct GlueSnapshot {
    root: PathBuf,
    /// Individually deleted files.
    files: Files,
    /// Deleted directories, each with its own file list.
    dirs: Vec<(PathBuf, Files)>,
}

impl GlueSnapshot {
    /// Read every path [`nuke`] would delete into memory.
    ///
    /// A no-op when nothing would be deleted, so callers can take a snapshot
    /// unconditionally.
    pub fn capture(root: &Path) -> Self {
        let lib = root.join("lib");
        let gen_dir = root.join("lib/oxide_generated");

        let mut files = Vec::new();
        let entry = root.join("lib/oxide.dart");
        if entry.is_file()
            && std::fs::read_to_string(&entry)
                .is_ok_and(|c| c.starts_with(GENERATED_ENTRYPOINT_MARKER))
            && let Ok(bytes) = std::fs::read(&entry)
        {
            files.push((PathBuf::from("lib/oxide.dart"), bytes));
        }
        for p in find_generated_files(&lib) {
            if let Ok(bytes) = std::fs::read(&p)
                && let Ok(rel) = p.strip_prefix(root)
            {
                files.push((rel.to_path_buf(), bytes));
            }
        }

        let mut dirs = Vec::new();
        if gen_dir.is_dir() {
            let mut contents = Vec::new();
            let mut stack = vec![gen_dir.clone()];
            while let Some(d) = stack.pop() {
                let Ok(rd) = std::fs::read_dir(&d) else {
                    continue;
                };
                for e in rd.flatten() {
                    let p = e.path();
                    if p.is_dir() {
                        stack.push(p);
                    } else if let (Ok(bytes), Ok(rel)) =
                        (std::fs::read(&p), p.strip_prefix(&gen_dir))
                    {
                        contents.push((rel.to_path_buf(), bytes));
                    }
                }
            }
            dirs.push((PathBuf::from("lib/oxide_generated"), contents));
        }

        Self {
            root: root.to_path_buf(),
            files,
            dirs,
        }
    }

    /// True when there was nothing to preserve.
    pub fn is_empty(&self) -> bool {
        self.files.is_empty() && self.dirs.is_empty()
    }

    /// Number of top-level paths captured, for reporting.
    pub fn len(&self) -> usize {
        self.files.len() + self.dirs.len()
    }

    /// Put back everything [`nuke`] removed.
    ///
    /// Best effort: a failure to restore one file does not abort the rest, since
    /// the alternative is losing more of the project than necessary.
    pub fn restore(&self) {
        for (rel, contents) in &self.dirs {
            let dir = self.root.join(rel);
            for (inner, bytes) in contents {
                let path = dir.join(inner);
                if let Some(parent) = path.parent() {
                    let _ = std::fs::create_dir_all(parent);
                }
                let _ = std::fs::write(&path, bytes);
            }
        }
        for (rel, bytes) in &self.files {
            let path = self.root.join(rel);
            if let Some(parent) = path.parent() {
                let _ = std::fs::create_dir_all(parent);
            }
            let _ = std::fs::write(&path, bytes);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn seed(root: &Path) {
        std::fs::create_dir_all(root.join("lib/oxide_generated/routes")).unwrap();
        std::fs::create_dir_all(root.join("lib/src")).unwrap();
        std::fs::write(
            root.join("lib/oxide_generated/routes/r.g.dart"),
            "generated route glue",
        )
        .unwrap();
        std::fs::write(
            root.join("lib/oxide.dart"),
            "// Generated by oxide_generator\nx",
        )
        .unwrap();
        std::fs::write(root.join("lib/src/oxide.oxide.g.dart"), "per-file glue").unwrap();
        std::fs::write(root.join("lib/src/handwritten.dart"), "keep me").unwrap();
    }

    #[test]
    fn nuke_removes_generated_and_keeps_handwritten() {
        let dir = tempfile::tempdir().unwrap();
        seed(dir.path());
        nuke(dir.path());

        assert!(!dir.path().join("lib/oxide_generated").exists());
        assert!(!dir.path().join("lib/oxide.dart").exists());
        assert!(!dir.path().join("lib/src/oxide.oxide.g.dart").exists());
        assert!(dir.path().join("lib/src/handwritten.dart").exists());
    }

    #[test]
    fn nuke_leaves_hand_written_oxide_dart_alone() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(dir.path().join("lib")).unwrap();
        std::fs::write(
            dir.path().join("lib/oxide.dart"),
            "// my own barrel\nexport 'a.dart';",
        )
        .unwrap();
        nuke(dir.path());
        assert!(dir.path().join("lib/oxide.dart").exists());
    }

    #[test]
    fn snapshot_restore_round_trips_after_nuke() {
        let dir = tempfile::tempdir().unwrap();
        seed(dir.path());

        let snap = GlueSnapshot::capture(dir.path());
        assert!(!snap.is_empty());

        nuke(dir.path());
        snap.restore();

        assert_eq!(
            std::fs::read_to_string(dir.path().join("lib/oxide_generated/routes/r.g.dart"))
                .unwrap(),
            "generated route glue"
        );
        assert_eq!(
            std::fs::read_to_string(dir.path().join("lib/src/oxide.oxide.g.dart")).unwrap(),
            "per-file glue"
        );
        assert!(dir.path().join("lib/oxide.dart").exists());
    }

    #[test]
    fn snapshot_of_clean_tree_is_empty() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(dir.path().join("lib")).unwrap();
        assert!(GlueSnapshot::capture(dir.path()).is_empty());
    }
}
