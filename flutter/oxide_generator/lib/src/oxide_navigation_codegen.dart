String _lowerCamel(String s) {
  if (s.isEmpty) return s;
  final parts = s
      .split(RegExp(r'[_\-\s]+'))
      .where((p) => p.isNotEmpty)
      .toList(growable: false);
  if (parts.isEmpty) return s;

  final first = parts.first;
  final firstLower = first[0].toLowerCase() + first.substring(1);
  if (parts.length == 1) return firstLower;

  final rest = parts
      .skip(1)
      .map((p) => p.isEmpty ? p : (p[0].toUpperCase() + p.substring(1)))
      .join();
  return '$firstLower$rest';
}

String _upperCamel(String s) {
  if (s.isEmpty) return s;
  final lower = _lowerCamel(s);
  if (lower.isEmpty) return lower;
  return lower[0].toUpperCase() + lower.substring(1);
}

String _snakeCase(String s) {
  if (s.isEmpty) return s;
  final withUnderscores = s.replaceAllMapped(
    RegExp(r'(?<!^)([A-Z])'),
    (m) => '_${m[1]}',
  );
  return withUnderscores.toLowerCase();
}

String _dartTypeFromRust(String rustType) {
  final normalized = rustType.replaceAll(' ', '');
  final optionMatch = RegExp(r'^Option<(.+)>$').firstMatch(normalized);
  if (optionMatch != null) {
    return '${_dartTypeFromRust(optionMatch.group(1)!)}?';
  }
  final vecMatch = RegExp(r'^Vec<(.+)>$').firstMatch(normalized);
  if (vecMatch != null) {
    return 'List<${_dartTypeFromRust(vecMatch.group(1)!)}>';
  }
  final boxMatch = RegExp(r'^(Box|Arc|Rc)<(.+)>$').firstMatch(normalized);
  if (boxMatch != null) {
    return _dartTypeFromRust(boxMatch.group(2)!);
  }
  final mapMatch = RegExp(r'^(HashMap|BTreeMap)<(.+)>$').firstMatch(normalized);
  if (mapMatch != null) {
    final args = _splitRustGenericArgs(mapMatch.group(2)!);
    if (args.length == 2) {
      return 'Map<${_dartTypeFromRust(args[0])}, ${_dartTypeFromRust(args[1])}>';
    }
  }
  final base = _stripRustPath(normalized);
  switch (base) {
    case 'String':
    case 'str':
      return 'String';
    case 'bool':
      return 'bool';
    case 'f32':
    case 'f64':
      return 'double';
    case 'i8':
    case 'i16':
    case 'i32':
    case 'isize':
    case 'u8':
    case 'u16':
    case 'u32':
    case 'usize':
      return 'int';
    case 'i64':
    case 'u64':
    case 'i128':
    case 'u128':
      return 'BigInt';
    default:
      return base;
  }
}

String _stripRustPath(String s) {
  final parts = s.split('::');
  return parts.isEmpty ? s : parts.last;
}

List<String> _splitRustGenericArgs(String s) {
  final args = <String>[];
  final buf = StringBuffer();
  var depth = 0;
  for (var i = 0; i < s.length; i++) {
    final ch = s[i];
    if (ch == '<') depth++;
    if (ch == '>') depth--;
    if (ch == ',' && depth == 0) {
      args.add(buf.toString());
      buf.clear();
      continue;
    }
    buf.write(ch);
  }
  if (buf.isNotEmpty) {
    args.add(buf.toString());
  }
  return args
      .map((a) => a.trim())
      .where((a) => a.isNotEmpty)
      .toList(growable: false);
}

String? _readCargoPackageName() {
  final file = File('rust/Cargo.toml');
  if (!file.existsSync()) return null;
  final lines = file.readAsLinesSync();
  var inPackage = false;
  for (final raw in lines) {
    final line = raw.split('#').first.trim();
    if (line.isEmpty) continue;
    if (line.startsWith('[') && line.endsWith(']')) {
      inPackage = line == '[package]';
      continue;
    }
    if (!inPackage) continue;
    if (!line.startsWith('name')) continue;
    final parts = line.split('=');
    if (parts.length < 2) continue;
    final value = parts.sublist(1).join('=').trim();
    final trimmed = value.replaceAll('"', '').replaceAll("'", '');
    if (trimmed.isNotEmpty) return trimmed;
  }
  return null;
}

bool _sameRouteMeta(RustRouteMeta a, RustRouteMeta b) {
  if (a.kind != b.kind) return false;
  if (a.rustType != b.rustType) return false;
  if (a.path != b.path) return false;
  if (a.returnType != b.returnType) return false;
  if (a.extraType != b.extraType) return false;
  if (a.fields.length != b.fields.length) return false;
  for (var i = 0; i < a.fields.length; i++) {
    final af = a.fields[i];
    final bf = b.fields[i];
    if (af.name != bf.name) return false;
    if (af.type != bf.type) return false;
  }
  return true;
}

String? _routeKindKeyFromSource(String expr) {
  final s = expr.trim();
  if (s.isEmpty) return null;

  final strMatch = RegExp(r"""^(['"])(.*)\1$""").firstMatch(s);
  if (strMatch != null) {
    final raw = strMatch.group(2) ?? '';
    if (raw.isEmpty) return null;
    return _lowerCamel(raw);
  }

  final enumMatch = RegExp(r'^RouteKind\.([A-Za-z_]\w*)$').firstMatch(s);
  if (enumMatch != null) {
    final raw = enumMatch.group(1) ?? '';
    if (raw.isEmpty) return null;
    return _lowerCamel(raw);
  }

  return null;
}
