final class RustChannelMetadata {
  RustChannelMetadata({
    required this.events,
    required this.callbacks,
    this.crateName,
    this.initFnName,
  });

  final List<RustEventChannelMeta> events;
  final List<RustCallbackMeta> callbacks;

  /// The name of the Rust crate that produced the metadata (e.g.
  /// `isolated_channels_demo`).
  final String? crateName;

  /// If available, the name of the Dart initialization function exposed by
  /// `isolated_channels_bridge.dart`. The generator will call this helper
  /// when setting up channels inside `OxideStack.init`.
  ///
  /// Tests may supply this manually; during normal builds we attempt to parse
  /// the bridge file to figure it out automatically.
  final String? initFnName;
}

final class RustEventChannelMeta {
  RustEventChannelMeta({required this.name, required this.eventType});

  /// Rust struct identifier, e.g. `CounterDemoEvents`.
  final String name;

  /// Dart type exposed for events, typically an enum imported from the
  /// generated `rust/.../channels.dart` file.
  final String eventType;
}

final class RustCallbackMeta {
  RustCallbackMeta({
    required this.name,
    required this.requestType,
    required this.responseType,
  });

  final String name;
  final String requestType;
  final String responseType;
}

Future<RustChannelMetadata> readRustChannelMetadata() async {
  final dir = Directory('rust/target/oxide_channels');
  final events = <RustEventChannelMeta>[];
  final callbacks = <RustCallbackMeta>[];
  final crateNames = <String>{};

  if (dir.existsSync()) {
    final files = dir
        .listSync(followLinks: false)
        .whereType<File>()
        .where((f) => f.path.endsWith('.json'))
        .toList(growable: false);

    for (final file in files) {
      final jsonStr = await file.readAsString();
      final obj = jsonDecode(jsonStr);
      if (obj is! Map<String, dynamic>) continue;

      if (obj['crate_name'] is String) {
        crateNames.add(obj['crate_name'] as String);
      }

      final rawEvents = obj['events'];
      if (rawEvents is List) {
        for (final raw in rawEvents) {
          if (raw is! Map<String, dynamic>) continue;
          final name = raw['name'];
          final eventType = raw['event_type'];
          if (name is String && eventType is String) {
            events.add(RustEventChannelMeta(name: name, eventType: eventType));
          }
        }
      }

      final rawCallbacks = obj['callbacks'];
      if (rawCallbacks is List) {
        for (final raw in rawCallbacks) {
          if (raw is! Map<String, dynamic>) continue;
          final name = raw['name'];
          final req = raw['request_type'];
          final resp = raw['response_type'];
          if (name is String && req is String && resp is String) {
            callbacks.add(
              RustCallbackMeta(
                name: name,
                requestType: req,
                responseType: resp,
              ),
            );
          }
        }
      }
    }
  }

  final String? crateName = crateNames.length == 1 ? crateNames.first : null;

  // attempt to infer the initialization helper from the bridge file, if it
  // exists. the bridge is generated by flutter_rust_bridge and lives next to
  // the metadata in `lib/src/rust/api`.
  String? initFnName;
  String? bridgeText;
  try {
    final bridgeFile = File('lib/src/rust/api/isolated_channels_bridge.dart');
    if (bridgeFile.existsSync()) {
      final text = await bridgeFile.readAsString();
      bridgeText = text;
      final match = RegExp(
        r'Future<\s*void\s*>\s*(init[^\(\s]+)\(',
      ).firstMatch(text);
      if (match != null) initFnName = match.group(1);
    }
  } catch (_) {
    // best effort; ignore failures
  }

  if (events.isEmpty && callbacks.isEmpty && bridgeText != null) {
    _inferChannelsFromBridge(bridgeText, events: events, callbacks: callbacks);
  }

  return RustChannelMetadata(
    events: events,
    callbacks: callbacks,
    crateName: crateName,
    initFnName: initFnName,
  );
}

void _inferChannelsFromBridge(
  String text, {
  required List<RustEventChannelMeta> events,
  required List<RustCallbackMeta> callbacks,
}) {
  final eventRegex = RegExp(
    r'Stream<\s*([A-Za-z0-9_]+)\s*>\s+([A-Za-z0-9_]+)Stream\s*\(',
  );
  for (final match in eventRegex.allMatches(text)) {
    final eventType = match.group(1);
    final baseName = match.group(2);
    if (eventType == null || baseName == null) continue;
    if (eventType.endsWith('PendingRequest')) continue;
    if (baseName.toLowerCase().contains('duplex')) continue;
    final name = _upperCamel(baseName);
    events.add(RustEventChannelMeta(name: name, eventType: eventType));
  }

  final callbackRegex = RegExp(
    r'Stream<\s*([A-Za-z0-9_]+PendingRequest)\s*>\s+([A-Za-z0-9_]+)RequestsStream\s*\(',
  );
  for (final match in callbackRegex.allMatches(text)) {
    final pendingType = match.group(1);
    final baseName = match.group(2);
    if (pendingType == null || baseName == null) continue;
    final name = _upperCamel(baseName);
    final requestType = _findRequestType(text, pendingType);
    final responseType = _findResponseType(text, baseName);
    if (requestType == null || responseType == null) continue;
    callbacks.add(
      RustCallbackMeta(
        name: name,
        requestType: requestType,
        responseType: responseType,
      ),
    );
  }
}

String? _findRequestType(String text, String pendingType) {
  final regex = RegExp(
    'class\\s+$pendingType\\s*\\{[\\s\\S]*?final\\s+([A-Za-z0-9_]+)\\s+request;',
  );
  return regex.firstMatch(text)?.group(1);
}

String? _findResponseType(String text, String baseName) {
  final regex = RegExp(
    'Future<\\s*void\\s*>\\s+${baseName}Respond\\s*\\(\\s*\\{[\\s\\S]*?required\\s+([A-Za-z0-9_]+)\\s+response',
  );
  return regex.firstMatch(text)?.group(1);
}

